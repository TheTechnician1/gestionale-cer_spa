@Injectable({ providedIn: 'root' })
export class I18nService {
  private readonly langSubject = new BehaviorSubject<Lang>(this.readLanguage());
  readonly lang$ = this.langSubject.asObservable();
  readonly languages: Lang[] = ['it', 'en', 'fr'];

  current(): Lang {
    return this.langSubject.value;
  }

  setLanguage(lang: Lang): void {
    localStorage.setItem(STORAGE_KEY, lang);
    this.langSubject.next(lang);
  }

  t(key: string): string {
    return DICTIONARY[this.current()][key] || DICTIONARY.it[key] || key;
  }

  private readLanguage(): Lang {
    const value = localStorage.getItem(STORAGE_KEY);
    return value === 'en' || value === 'fr' || value === 'it' ? value : 'it';
  }
}
